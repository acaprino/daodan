#!/usr/bin/env node
/**
 * Development rebuild of the vendored open-slide PPTX bundle.
 *
 * Copies the pinned engine sources and the Office entry into a work directory
 * outside the plugin, installs the pinned build inputs there, bundles one IIFE
 * and writes the bundle plus a hash manifest back into this directory. Nothing
 * is installed inside the plugin, so no node_modules tree can reach a host
 * package. The committed bundle is what the conversion driver injects.
 *
 * Usage:
 *   node rebuild.mjs [--workdir PATH] [--no-minify] [--skip-install] [--check]
 *
 * --check rebuilds without writing and reports drift against the committed
 * bundle and manifest. Exit codes: 0 clean, 1 drift or build failure,
 * 2 invocation error.
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';

const LIB = path.dirname(fileURLToPath(import.meta.url));
const ENTRY = path.join(LIB, 'entry', 'office-entry.ts');
const BUNDLE_DIR = path.join(LIB, 'bundle');
const BUNDLE = path.join(BUNDLE_DIR, 'open-slide-pptx.js');
const MANIFEST = path.join(LIB, 'manifest.json');
const BUILD_INPUTS = path.join(LIB, 'build.deps.json');

function fail(message) {
  process.stderr.write(message + '\n');
  process.exit(2);
}

function repoRoot(start) {
  let current = start;
  for (;;) {
    if (fs.existsSync(path.join(current, '.git'))) return current;
    const parent = path.dirname(current);
    if (parent === current) return start;
    current = parent;
  }
}

function sha256(file) {
  return crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
}

function sha256Bytes(bytes) {
  return crypto.createHash('sha256').update(bytes).digest('hex');
}

function walk(root) {
  const out = [];
  for (const entry of fs.readdirSync(root, { withFileTypes: true })) {
    const full = path.join(root, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.isFile()) out.push(full);
  }
  return out.sort();
}

function copyTree(source, target) {
  fs.mkdirSync(target, { recursive: true });
  for (const file of walk(source)) {
    const relative = path.relative(source, file);
    const destination = path.join(target, relative);
    fs.mkdirSync(path.dirname(destination), { recursive: true });
    fs.copyFileSync(file, destination);
  }
}

function parseArgs(argv) {
  const options = { workdir: null, minify: true, skipInstall: false, check: false };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--workdir') {
      index += 1;
      if (index >= argv.length) fail('--workdir needs a path');
      options.workdir = argv[index];
    } else if (arg === '--no-minify') options.minify = false;
    else if (arg === '--skip-install') options.skipInstall = true;
    else if (arg === '--check') options.check = true;
    else fail(`Unknown argument: ${arg}`);
  }
  return options;
}

function installedVersion(workdir, name) {
  try {
    const manifest = JSON.parse(fs.readFileSync(path.join(workdir, 'node_modules', name, 'package.json'), 'utf8'));
    return manifest.version;
  } catch {
    return null;
  }
}

function banner(upstream) {
  return [
    '/*',
    ' * Office HTML to PPTX bundle. Generated by rebuild.mjs; do not edit.',
    ' * Contains verbatim portions of open-slide (https://github.com/open-slide/open-slide),',
    ` * ${upstream.package} ${upstream.version} at commit ${upstream.git_ref}, MIT License,`,
    ' * notice in LICENSE-open-slide-MIT.txt, plus fflate (MIT, LICENSE-fflate-MIT.txt)',
    ' * and html-to-image (MIT, LICENSE-html-to-image-MIT.txt).',
    ' * The Office entry wrapper is MIT. Pin, hashes and refresh protocol: UPSTREAM.md.',
    ' */',
    '',
  ].join('\n');
}

/**
 * Run npm without a shell. Windows refuses to spawn npm.cmd directly since the
 * 2024 batch-file hardening, so npm's own CLI script runs under this Node.
 */
function runNpm(args, cwd) {
  const nodeDir = path.dirname(process.execPath);
  const scripts = [
    process.env.npm_execpath,
    path.join(nodeDir, 'node_modules', 'npm', 'bin', 'npm-cli.js'),
    path.join(nodeDir, '..', 'lib', 'node_modules', 'npm', 'bin', 'npm-cli.js'),
  ].filter((candidate) => candidate && candidate.endsWith('.js') && fs.existsSync(candidate));
  const result = scripts.length > 0
    ? spawnSync(process.execPath, [scripts[0], ...args], { cwd, stdio: 'inherit' })
    : process.platform === 'win32'
      ? { status: null, error: new Error(`npm-cli.js was not found beside ${process.execPath}`) }
      : spawnSync('npm', args, { cwd, stdio: 'inherit' });
  if (result.status !== 0) {
    fail(`npm ${args[0]} failed in ${cwd}: ${result.error ? result.error.message : `exit ${result.status}`}`);
  }
}

async function main() {
  const options = parseArgs(process.argv.slice(2));
  for (const required of [path.join(LIB, 'src'), ENTRY, BUILD_INPUTS]) {
    if (!fs.existsSync(required)) fail(`Missing rebuild input: ${required}`);
  }
  const workdir = options.workdir
    ? path.resolve(options.workdir)
    : path.join(repoRoot(LIB), '.daodan', 'tmp', 'open-slide-pptx-build');

  fs.mkdirSync(workdir, { recursive: true });
  const deps = JSON.parse(fs.readFileSync(BUILD_INPUTS, 'utf8'));
  const upstream = deps.upstream;
  if (!upstream || !upstream.version || !upstream.git_ref || !Array.isArray(upstream.copied_paths)) {
    fail(`build.deps.json lacks the upstream pin (version, git_ref, copied_paths): ${BUILD_INPUTS}`);
  }
  const pkg = {
    name: 'office-open-slide-pptx-build',
    private: true,
    version: '0.0.0',
    type: 'module',
    dependencies: deps.dependencies,
    devDependencies: deps.devDependencies,
  };
  fs.writeFileSync(path.join(workdir, 'package.json'), JSON.stringify(pkg, null, 2) + '\n');
  copyTree(path.join(LIB, 'src'), path.join(workdir, 'src'));
  copyTree(path.join(LIB, 'entry'), path.join(workdir, 'entry'));

  const viteEntry = path.join(workdir, 'node_modules', 'vite', 'dist', 'node', 'index.js');
  const needInstall = !options.skipInstall || !fs.existsSync(viteEntry);
  if (needInstall) runNpm(['install', '--no-audit', '--no-fund', '--loglevel=error'], workdir);
  if (!fs.existsSync(viteEntry)) fail(`Vite is not installed in ${workdir}; rerun without --skip-install`);

  const { build } = await import(pathToFileURL(viteEntry).href);
  await build({
    configFile: false,
    root: workdir,
    logLevel: 'warn',
    resolve: {
      alias: {
        fflate: path.join(workdir, 'node_modules', 'fflate', 'esm', 'browser.js'),
        'html-to-image': path.join(workdir, 'node_modules', 'html-to-image', 'es', 'index.js'),
      },
    },
    build: {
      outDir: path.join(workdir, 'dist'),
      emptyOutDir: true,
      minify: options.minify,
      lib: {
        entry: path.join(workdir, 'entry', 'office-entry.ts'),
        name: 'OfficeHtmlToPptx',
        formats: ['iife'],
        fileName: () => 'open-slide-pptx.js',
      },
    },
  });

  const built = path.join(workdir, 'dist', 'open-slide-pptx.js');
  if (!fs.existsSync(built)) fail(`Vite produced no bundle at ${built}`);
  const bundleBytes = Buffer.concat([Buffer.from(banner(upstream), 'utf8'), fs.readFileSync(built)]);
  const sourceFiles = walk(path.join(LIB, 'src')).concat([ENTRY]);
  const files = {};
  for (const file of sourceFiles) files[path.relative(LIB, file).replaceAll('\\', '/')] = sha256(file);
  files['bundle/open-slide-pptx.js'] = sha256Bytes(bundleBytes);

  if (options.check) {
    const differences = [];
    if (!fs.existsSync(BUNDLE)) differences.push('bundle/open-slide-pptx.js is missing');
    else if (sha256(BUNDLE) !== files['bundle/open-slide-pptx.js']) differences.push('bundle/open-slide-pptx.js differs from a fresh build');
    if (!fs.existsSync(MANIFEST)) differences.push('manifest.json is missing');
    else {
      const recorded = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
      if (JSON.stringify(recorded.upstream) !== JSON.stringify(upstream)) differences.push('manifest.json upstream differs from the build.deps.json pin');
      for (const [name, digest] of Object.entries(files)) {
        if ((recorded.files || {})[name] !== digest) differences.push(`${name} differs from manifest.json`);
      }
      for (const name of Object.keys(recorded.files || {})) {
        if (!(name in files)) differences.push(`${name} is recorded in manifest.json but absent`);
      }
    }
    process.stdout.write(JSON.stringify({
      status: differences.length === 0 ? 'clean' : 'drift',
      differences,
      bundle_sha256: files['bundle/open-slide-pptx.js'],
      minify: options.minify,
      workdir,
    }) + '\n');
    process.exit(differences.length === 0 ? 0 : 1);
  }

  fs.mkdirSync(BUNDLE_DIR, { recursive: true });
  fs.writeFileSync(BUNDLE, bundleBytes);
  const manifest = {
    schema: 'office/open-slide-pptx-manifest/v1',
    upstream,
    third_party: [
      { package: 'fflate', version: installedVersion(workdir, 'fflate'), license: 'MIT', notice: 'LICENSE-fflate-MIT.txt' },
      { package: 'html-to-image', version: installedVersion(workdir, 'html-to-image'), license: 'MIT', notice: 'LICENSE-html-to-image-MIT.txt' },
    ],
    tools: {
      node: process.version,
      vite: installedVersion(workdir, 'vite'),
      minify: options.minify,
      format: 'iife',
      global: 'officeHtmlToPptx',
    },
    bundle: {
      path: 'bundle/open-slide-pptx.js',
      sha256: files['bundle/open-slide-pptx.js'],
      bytes: bundleBytes.length,
    },
    files: Object.fromEntries(Object.entries(files).sort(([a], [b]) => a.localeCompare(b))),
  };
  fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 2) + '\n');
  process.stdout.write(JSON.stringify({
    status: 'built',
    bundle: path.relative(LIB, BUNDLE).replaceAll('\\', '/'),
    bundle_bytes: bundleBytes.length,
    bundle_sha256: manifest.bundle.sha256,
    hashed_files: Object.keys(manifest.files).length,
    minify: options.minify,
    workdir,
  }) + '\n');
}

main().catch((error) => {
  process.stderr.write(`rebuild failed: ${error && error.stack ? error.stack : error}\n`);
  process.exit(1);
});
