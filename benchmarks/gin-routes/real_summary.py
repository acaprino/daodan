"""From the answers of `modal_real.py` (`$GIN_ROUTES_EVIDENCE/<name>.noir.json` and `<name>.go.json`, outside the repository) to the counts of
the README's «Applicazioni vere»: `results/real/<name>.json` and `results/real/summary.json`, and the tables printed.

    python -I benchmarks/gin-routes/real_summary.py <the evidence folder>

It reads recorded data only. The Noir side is `benchmarks/noir-binding` as it is: `causes.cause` over `measure.py`'s rows gives the endpoints
for which Noir names no handler (calibrated: 237 on the three applications), `after.py`'s rows the binder's answer. The Gin side: the routes the
hook wrote (way c) and those of `Routes()` (way a), each handler placed by its file and line (from the pc, or from the name with `go tool nm`
and `go tool addr2line`) in the snapshot's Go functions (`real.py`, `noir_stage`). A route of each side is met by method and path schema
(`flows.path_schema`, computed in the container), else by method and the line that registers it (Noir's `code_paths`, the hook's first frame
outside Gin). The comparator that builds and runs nothing: the call of Gin at the line Noir cites and the function its last argument names, as
go/types resolves it (`finder`, `handler_calls`). The tiers of a run are the first word of its label (`modal_real.VARIANTS`). Only counts and
short excerpts (route, handler name, file:line) are written.
"""
import collections
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "noir-binding"))
import causes  # noqa: E402

OUT = HERE / "results" / "real"
EXPECTED = {"gin-vue-admin": (217, 207, 1), "go-admin": (139, 15, 93), "go-gin-example": (29, 15, 0)}  # http, no handler, named (noir-binding)
SHOWN = 6


def rel(path: str | None) -> str | None:
    if not path:
        return None
    return path[len("/copy/"):] if path.startswith("/copy/") else None


def split_site(text: str | None) -> tuple[str | None, int | None]:
    if not text or ":" not in text:
        return None, None
    file, _, line = text.rpartition(":")
    return file, int(line) if line.isdecimal() else None


def place(file_line: tuple[str | None, int | None], functions: dict) -> dict:
    """Where a file and a line fall among the snapshot's Go functions of that file."""
    path, line = file_line
    if path is None or line is None:
        return {"level": "no file and line"}
    file = rel(path)
    if file is None:
        return {"level": "outside the project", "file": path.split("/gomod/")[-1].split("/usr/local/go/")[-1][:90], "line": line}
    declared = functions.get(file, [])
    if not declared:
        return {"level": "a file without functions in the snapshot", "file": file}
    starts = [d for d in declared if d["line"] == line]
    covering = sorted((d for d in declared if d["line"] <= line <= (d["end"] or d["line"])), key=lambda d: (d["end"] or d["line"]) - d["line"])
    out = {"file": file, "line": line}
    if len(starts) == 1:
        d = starts[0]
        out.update({"level": "one function starts at the line", "function": d})
    elif starts:
        out.update({"level": "several functions start at the line", "function": None})
    elif covering:
        out.update({"level": "only covered (no function starts at the line)", "function": covering[0]})
    else:
        out.update({"level": "no function covers the line", "function": None})
    return out


def expected_name(parts: dict | None) -> str | None:
    """The snapshot's way of writing the function `debug/gosym` split: `Type.Method` for a method (`(*T)` read as `T`), the base for a function."""
    if not parts:
        return None
    base = parts["base"][:-3] if parts["base"].endswith("-fm") else parts["base"]
    receiver = parts["receiver"].strip("()").lstrip("*")
    return f"{receiver}.{base}" if receiver else base


def handler_place(name: str, info: dict, functions: dict, pc_file_line=None) -> dict:
    """A handler's file and line: from the pc when `Routes()` gave it, else from the name's symbol; a method value (`-fm`, the compiler's
    wrapper, `<autogenerated>:1`) from the method's own symbol."""
    via, file_line = None, (None, None)
    if pc_file_line and pc_file_line[0] and not pc_file_line[0].startswith("<"):
        via, file_line = "pc", pc_file_line
    else:
        symbol = (info.get("symbol") or {}).get("file_line")
        if symbol and not symbol.startswith("<"):
            via, file_line = "name", split_site(symbol)
        elif info.get("method_symbol") and (info["method_symbol"] or {}).get("file_line"):
            via, file_line = "name without -fm", split_site(info["method_symbol"]["file_line"])
        elif symbol:
            via = "autogenerated, no method symbol" if name.endswith("-fm") else "autogenerated"
    out = {"via": via, **place(file_line, functions)}
    function = out.get("function")
    if function:
        wanted = expected_name(info.get("gosym"))
        out["agrees"] = function["name"] == wanted or (function["name"].startswith("(") and ".func" in (wanted or ""))
        out["node"] = node_of(function)
    return out


def node_of(function: dict) -> str:
    """The function's node as the links have it (`Facts.node`, `named`): its own and of no other function, its own and shared, folded, none."""
    return "own, one function" if function["node"] == function["named"] and function["same_named"] == 1 else (
        "own, shared by several functions" if function["node"] == function["named"] else "folded into another" if function["node"] else "no node")


def static_place(calls: list[dict], functions: dict) -> dict:
    """Without building or running: the one call of Gin with a `...gin.HandlerFunc` parameter at the line Noir cites, and the function its last
    argument names as the type checker resolves it (the finder, go/types), placed among the snapshot's functions."""
    if not calls:
        return {"level": "no call of Gin at the line"}
    if len(calls) > 1:
        return {"level": "several calls of Gin at the line"}
    last = calls[0]["last"]
    if last["kind"] not in ("function", "method", "function literal") or not last.get("pos"):
        return {"level": f"the last argument is a {last['kind']}", "kind": last["kind"], "callee": last.get("callee"), "spread": calls[0]["spread"]}
    file, line = split_site(last["pos"])
    out = {"kind": last["kind"], "spread": calls[0]["spread"], **place(("/copy/" + file if not file.startswith("..") else file, line), functions)}
    if out.get("function"):
        out["node"] = node_of(out["function"])
    return out


def short(function: dict | None) -> str | None:
    return f"{function['name']} {function['line']}-{function['end']}" if function else None


def summarize(name: str, folder: pathlib.Path) -> dict:
    noir = json.loads((folder / f"{name}.noir.json").read_text(encoding="utf-8"))
    go = json.loads((folder / f"{name}.go.json").read_text(encoding="utf-8"))
    if noir.get("failed") or go.get("failed"):
        return {"name": name, "failed": noir.get("failed") or go.get("failed")}
    functions = collections.defaultdict(list)
    for d in noir["go_functions"]:
        functions[d["file"]].append(d)
    measure = noir["measure"]
    http = [r for r in measure["rows"] if causes.stage(r) == "http"]
    for r in http:
        r["group"] = None if r.get("ok") else causes.cause(r)[0]
    no_handler = [r for r in http if r["group"] == causes.NO_HANDLER]
    named = [r for r in http if r.get("row_handler")]
    calibration = (len(http), len(no_handler), len(named))
    after_rows = {(f["method"], f["path"], f["site"]): f for f in noir["after"]["facts"] if f["shape"] == "http"}

    def after_of(r):
        return after_rows.get((r["method"], r["url"], f"{r['file']}:{r['line']}" if r.get("line") else r.get("file")))

    out = {"name": name, "calibration": {"http": calibration[0], "no_handler": calibration[1], "named": calibration[2], "expected": EXPECTED.get(name),
                                         "matches": calibration == EXPECTED.get(name)},
           "noir_bound_now": sum(1 for r in http if (after_of(r) or {}).get("ok")), "noir_rows_without_after": sum(1 for r in http if after_of(r) is None),
           "snapshot_seconds": measure.get("snapshot_seconds"), "go_functions": len(noir["go_functions"]),
           "prepared": go.get("prepared"), "go": go.get("go"), "x_tools": go.get("x_tools"),
           "left_in_the_copy": go.get("left_in_the_copy"), "left_count": go.get("left_count"), "changed_in_the_copy": go.get("changed_in_the_copy"),
           "gomod_bytes": go.get("gomod_bytes")}
    out["modules"] = {m: {k: info["finder"].get(k) for k in ("engine_builders", "engine_calls", "main_packages", "registrars", "load_error_count", "seconds",
                                                            "peak_memory_mb", "returncode")} | {"handler_factories": len(info["finder"].get("handler_factories") or ())}
                      for m, info in go["modules"].items()}
    out["builds"] = {d: {"module": b["module"], "built": bool(b["binary"]), "mod_flag": b["mod_flag"],
                         "attempts": [{k: a[k] for k in ("returncode", "seconds", "peak_memory_mb")} | {"stderr_tail": a["stderr_tail"][-400:]} for a in b["builds"]]}
                     for d, b in go["built"].items()}
    factories = {f["package"] + "." + f["name"] for info in go["modules"].values() for f in info["finder"].get("handler_factories") or ()}

    # the routes of each run (way c, the hook; way b, Gin's own text, only counted) and of each probe (way a, `Routes()`)
    def key(line):
        return (line["method"], line.get("schema") or line["path"])

    tiers = ("none", "Dockerfile", "CI", "by hand")  # the first word of a run's label: where its argument list comes from (`modal_real.VARIANTS`)
    runs, sets = [], {**{t: {} for t in tiers}, "Routes()": {}}
    for run in go["runs"]:
        routes = [l for l in run.get("lines", ()) if l.get("kind") == "route"]
        hook = next((l for l in run.get("lines", ()) if l.get("kind") == "hook"), {})
        item = {"dir": run["dir"], "argv": run["argv"], "label": run["label"], "tags": run.get("tags"), "plain": run.get("plain", False), "skipped": run.get("skipped")}
        if "run" in run:
            r = run["run"]
            item.update({"returncode": r["returncode"], "seconds": r["seconds"], "peak_memory_mb": r["peak_memory_mb"], "ended": r["ended"],
                         "debugging": hook.get("debugging"), "hook_routes": len(routes), "distinct": len({(l["method"], l["path"]) for l in routes}),
                         "debug_route_lines": run.get("debug_route_lines"), "before_steps": run.get("before_steps"),
                         "stderr_last": [x[:200] for x in r["stderr_tail"].strip().splitlines()[-2:]]})
        runs.append(item)
        target = sets[next(t for t in tiers if run["label"].startswith(t))]
        for l in routes:
            target.setdefault(key(l), {"line": l, "symbols": run.get("symbols") or {}})
    out["runs"] = runs
    probes = []
    for probe in go["probes"]:
        got = [l for l in probe.get("lines", ()) if l.get("kind") == "routes"]
        hooked = [l for l in probe.get("lines", ()) if l.get("kind") == "route"]
        panic = next((l["value"][:200] for l in probe.get("lines", ()) if l.get("kind") == "panic"), None)
        r = probe.get("run") or {}
        probes.append({"builder": f"{probe['builder']['package']}.{probe['builder']['name']}", "pos": probe["builder"]["pos"], "built": "run" in probe,
                       "build_seconds": probe["build"]["seconds"], "returncode": r.get("returncode"), "ended": r.get("ended"), "seconds": r.get("seconds"),
                       "peak_memory_mb": r.get("peak_memory_mb"), "routes_from_Routes": len(got), "routes_from_hook": len(hooked), "panic": panic,
                       "fm_handlers": sum(1 for l in got if l["handler"].endswith("-fm")),
                       "fm_autogenerated": sum(1 for l in got if l["handler"].endswith("-fm") and l["file"].startswith("<")),
                       "pc_is_entry": sum(1 for l in got if l.get("entry"))})
        for l in got:
            sets["Routes()"].setdefault(key(l), {"line": l, "symbols": probe.get("symbols") or {}})
    out["probes"] = probes

    callers = {}  # route -> the first frame outside Gin when it was registered (the hook's lines)
    for name_ in tiers:
        for k, v in sets[name_].items():
            first = (v["line"].get("callers") or [None])[0]
            if first and rel(first.get("file")):
                callers.setdefault(k, (rel(first["file"]), first["line"]))
    every = {}
    for name_ in ("Routes()", *tiers):  # `Routes()` first: its pc places a handler a name cannot (a generic function)
        for k, v in sets[name_].items():
            every.setdefault(k, v)
    placements = {}
    for k, v in every.items():
        line = v["line"]
        pc = (line.get("file"), line.get("line")) if "file" in line else None
        placements[k] = handler_place(line["handler"], v["symbols"].get(line["handler"], {}), functions, pc)
    # cumulative: what Daodan could run with nothing read (no argument, and the constructors the finder lists), then what the Dockerfile says,
    # then the build tags of the CI, then the services and settings written by hand
    views, taken = {}, {"Routes()"}
    for tier in tiers:
        taken.add(tier)
        views["+ " + tier if tier != "none" else "none and Routes()"] = [k for k in every if any(k in sets[t] for t in taken)]

    out["gin"] = {"routes": {n: len(v) for n, v in sets.items()}, "routes_every": len(every),
                  "levels": dict(collections.Counter(p["level"] for p in placements.values())),
                  "via": dict(collections.Counter(p["via"] for p in placements.values())),
                  "nodes": dict(collections.Counter(p.get("node") for p in placements.values() if p.get("function"))),
                  "name_agrees": dict(collections.Counter(p.get("agrees") for p in placements.values() if p.get("function"))),
                  "handler_from_a_factory_of_the_project": sum(1 for v in every.values() if any(v["line"]["handler"].startswith((f + ".func", f + "[")) for f in factories)),
                  "generic_names": sum(1 for v in every.values() if "[...]" in v["line"]["handler"]),
                  "handlers_in_chain": dict(collections.Counter(v["line"].get("handlers") for v in every.values() if "handlers" in v["line"])),
                  "registration_frame_in_the_project": sum(1 for k in every if k in callers)}
    out["gin"]["examples"] = [{"route": f"{k[0]} {k[1]}", "handler": every[k]["line"]["handler"][-90:], "via": p["via"], "level": p["level"],
                               "at": f"{p.get('file')}:{p.get('line')}", "function": short(p.get("function"))} for k, p in list(placements.items())[:SHOWN]]

    # Noir against Gin: by method and path schema, else by method and the line that registers the route (Noir's `code_paths`, the hook's first frame)
    registered = collections.defaultdict(list)
    for k, site in callers.items():
        registered[(k[0], *site)].append(k)

    def key_of(r):
        return (r["method"], r.get("schema") or r["url"])

    def meet(r, view):
        if key_of(r) in view:
            return key_of(r), "path"
        cited = r.get("code_path") or {}
        found = [k for k in registered.get((r["method"], cited.get("path"), cited.get("line")), ()) if k in view]
        return (found[0], "registration line") if len(found) == 1 else (None, "ambiguous registration line" if found else None)

    out["noir_vs_gin"] = {}
    for view_name, keys in views.items():
        view = set(keys)
        result = {}
        for label, rows in {"named": named, "no_handler": no_handler, "all_http": http}.items():
            met = [(r, *meet(r, view)) for r in rows]
            hit = [(r, k) for r, k, _how in met if k]
            result[label] = {"rows": len(rows), "met": len(hit), "how": dict(collections.Counter(how for _r, k, how in met if how)),
                             "levels": dict(collections.Counter(placements[k]["level"] for _r, k in hit)),
                             "one_function_own_node": sum(1 for _r, k in hit if placements[k]["level"] == "one function starts at the line"
                                                          and placements[k].get("node") == "own, one function"),
                             # how those were placed: from the pc, from the name as written, or only from the name without `-fm`
                             "one_function_own_node_by_via": dict(collections.Counter(
                                 placements[k]["via"] for _r, k in hit if placements[k]["level"] == "one function starts at the line"
                                 and placements[k].get("node") == "own, one function")),
                             "registration_line_equal": sum(1 for r, k in hit if callers.get(k) == ((r.get("code_path") or {}).get("path"),
                                                                                                   (r.get("code_path") or {}).get("line")))}
        met_keys = {meet(r, view)[0] for r in http} - {None}
        only_gin = [k for k in keys if k not in met_keys]
        only_noir = [r for r in http if meet(r, view)[0] is None]
        result["only_gin"] = {"count": len(only_gin), "levels": dict(collections.Counter(placements[k]["level"] for k in only_gin)),
                              "examples": [{"route": f"{k[0]} {k[1]}", "handler": every[k]["line"]["handler"][-80:],
                                            "registered_at": "%s:%s" % callers[k] if k in callers else None} for k in only_gin[:SHOWN]]}
        result["only_noir"] = {"count": len(only_noir), "groups": dict(collections.Counter(r["group"] or "bound" for r in only_noir)),
                               "cited_files": dict(collections.Counter((r.get("code_path") or {}).get("path") for r in only_noir).most_common(8)),
                               "examples": [{"route": f"{r['method']} {r['url']}", "group": r["group"], "cites": f"{r.get('file')}:{r.get('line')}"}
                                            for r in only_noir[:SHOWN]]}
        out["noir_vs_gin"][view_name] = result

    # the endpoints Noir names, bound by Daodan's binder: does Gin's function agree?
    view = set(every)
    agree, disagreements = collections.Counter(), []
    for r in named:
        a = after_of(r) or {}
        k, _how = meet(r, view)
        if not a.get("ok"):
            agree["not bound by the binder"] += 1
        elif k is None:
            agree["not met by Gin"] += 1
        else:
            p = placements[k]
            f = p.get("function")
            same = f is not None and a.get("file") == p.get("file") and f["line"] == a["lines"][0]
            agree["same function" if same else "another function"] += 1
            if not same and len(disagreements) < SHOWN:
                disagreements.append({"route": f"{r['method']} {r['url']}", "noir": r.get("row_handler"), "binder": a.get("decl_brief"), "gin": short(f),
                                      "gin_level": p["level"]})
    out["named_agreement"] = dict(agree)
    out["named_disagreements"] = disagreements
    # the comparator that builds and runs nothing: the call of Gin at the line Noir cites and its last argument, resolved by go/types (finder)
    calls_at = collections.defaultdict(dict)
    for info in go["modules"].values():
        for c in info["finder"].get("handler_calls") or ():
            for site in (c["at"], c["start"]):
                calls_at[site][id(c)] = c
    statics = {}
    for r in http:
        cited = r.get("code_path") or {}
        statics[id(r)] = static_place(list(calls_at.get(f"{cited.get('path')}:{cited.get('line')}", {}).values()), functions)
    out["static"] = {"handler_calls": sum(len(info["finder"].get("handler_calls") or ()) for info in go["modules"].values())}
    for label, rows in {"named": named, "no_handler": no_handler, "all_http": http}.items():
        placed_ = [statics[id(r)] for r in rows]
        out["static"][label] = {"rows": len(rows), "levels": dict(collections.Counter(p["level"] for p in placed_)),
                                "kinds": dict(collections.Counter(p.get("kind") for p in placed_ if p.get("kind"))),
                                "one_function_own_node": sum(1 for p in placed_ if p["level"] == "one function starts at the line"
                                                             and p.get("node") == "own, one function"),
                                "spread": sum(1 for p in placed_ if p.get("spread"))}
    both = collections.Counter()
    for r in http:
        k, _how = meet(r, view)
        st = statics[id(r)]
        if k is None or not placements[k].get("function") or not st.get("function"):
            continue
        g = placements[k]["function"]
        both["same function" if (g["file"], g["line"]) == (st["function"]["file"], st["function"]["line"]) else "another function"] += 1
    out["static"]["against_gin"] = dict(both)
    # of the endpoints without Noir's handler: placed on one function by only one of the two (Gin with every run, or the type checker)
    one = "one function starts at the line"
    gin_one = {id(r) for r in no_handler if (k := meet(r, view)[0]) is not None and placements[k]["level"] == one}
    static_one = {id(r) for r in no_handler if statics[id(r)]["level"] == one}
    out["static"]["no_handler_only_gin"] = [{"route": f"{r['method']} {r['url']}", "static": statics[id(r)]["level"],
                                             "gin": short(placements[meet(r, view)[0]].get("function"))} for r in no_handler if id(r) in gin_one - static_one]
    out["static"]["no_handler_only_static"] = [{"route": f"{r['method']} {r['url']}", "function": short(statics[id(r)].get("function")),
                                                "gin": (lambda k: placements[k]["level"] if k else "not met by Gin")(meet(r, view)[0])}
                                               for r in no_handler if id(r) in static_one - gin_one][:SHOWN]
    out["static"]["no_handler_only_static_count"] = len(static_one - gin_one)
    against = collections.Counter()
    for r in named:
        a, st = after_of(r) or {}, statics[id(r)]
        if not a.get("ok"):
            against["not bound by the binder"] += 1
        elif not st.get("function"):
            against["no function from the call"] += 1
        else:
            same = (a.get("file"), a["lines"][0]) == (st["function"]["file"], st["function"]["line"])
            against["same function as the binder" if same else "another function"] += 1
    out["static"]["named_against_the_binder"] = dict(against)
    out["static"]["examples"] = [{"route": f"{r['method']} {r['url']}",
                                  "noir_cites": f"{(r.get('code_path') or {}).get('path')}:{(r.get('code_path') or {}).get('line')}",
                                  "level": statics[id(r)]["level"], "kind": statics[id(r)].get("kind"), "function": short(statics[id(r)].get("function")),
                                  "callee": statics[id(r)].get("callee")} for r in no_handler[:SHOWN]]
    out["static"]["not_placed"] = [{"route": f"{r['method']} {r['url']}", "level": statics[id(r)]["level"], "callee": statics[id(r)].get("callee"),
                                    "at": f"{statics[id(r)].get('file')}:{statics[id(r)].get('line')}"}
                                   for r in no_handler if statics[id(r)]["level"] != "one function starts at the line"][:SHOWN + 4]
    out["no_handler_examples"] = []
    for r in no_handler:
        k, how = meet(r, view)
        if k and len(out["no_handler_examples"]) < SHOWN + 2:
            p = placements[k]
            cited = r.get("code_path") or {}
            out["no_handler_examples"].append({"route": f"{r['method']} {r['url']}", "met_by": how, "noir_cites": f"{cited.get('path')}:{cited.get('line')}",
                                               "gin_handler": every[k]["line"]["handler"][-80:], "at": f"{p.get('file')}:{p.get('line')}",
                                               "function": short(p.get("function")), "level": p["level"]})
    return out


def main(folder: pathlib.Path) -> None:
    sys.stdout.reconfigure(encoding="utf-8")  # the applications write Chinese; `-I` ignores PYTHONIOENCODING
    OUT.mkdir(parents=True, exist_ok=True)
    every = {}
    for name in EXPECTED:
        if not (folder / f"{name}.go.json").is_file() or not (folder / f"{name}.noir.json").is_file():
            print(name, "missing")
            continue
        answer = summarize(name, folder)
        every[name] = answer
        (OUT / f"{name}.json").write_bytes((json.dumps(answer, indent=1, ensure_ascii=False) + "\n").encode("utf-8"))
        if answer.get("failed"):
            print(name, "FAILED", answer["failed"][-300:])
            continue
