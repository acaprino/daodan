// Exact recorder of the calls a Go test run executes: a rewrite of the modules' sources with the toolchain's own
// parser, in the copy a container holds, never in the project.
//
//	go run go_record.go <copy root> <table.json> <module folder>...
//	DAODAN_GO_RECORD=<calls.tsv> go test -vet=off ./...     (in each module folder)
//
// The compiler has no hook that reports calls, and pprof samples. `go test -cover` rewrites the sources it
// compiles; this does the same with two insertions that keep every line where it was:
//
//   - a function body starts with `daodanrec.Enter(id)`: the function says it was entered. Enter asks the runtime
//     for its caller's frame (runtime.Callers, runtime.CallersFrames: logical frames, inlined ones included) and
//     appends `id <tab> caller file <tab> caller line` to DAODAN_GO_RECORD, once per caller position.
//   - a call's opening parenthesis sits between two line directives, `f/*line :N:1*/(/*line :L:C*/x)`: the
//     compiler places a call at its parenthesis (cmd/compile/internal/syntax, pexpr), so the caller's frame
//     reports line N, a number past the file's last line that names this one call, and the second directive
//     gives the next character its real position. Two calls on one line are two sites.
//
// The table lists, per file (its path from the copy root), its line count and its calls in the order of their
// numbers (line, column, name: the callee's name token, or where a callee without a name starts), every function
// by id (file, line, column of its `func`, name) and each module folder's path: lines from 1, columns in bytes
// from 1. Ids run across the modules: one module's test may enter another's code.
//
// Not recorded: a callee outside the modules (standard library, dependencies: not rewritten); a function the
// runtime or foreign code starts or calls back (a `go` statement, init, a callback from the standard library): it
// is entered with no site; a deferred call, which the compiler places at the function's end; sites in a file
// with line directives of its own or with `import "C"` (cgo prints the file again); code under vendor, testdata
// and directories the go tool ignores; a file with more lines and calls than a line number holds; a process
// without DAODAN_GO_RECORD. A test that asserts on the line numbers runtime.Caller reports sees the site numbers.
package main

import (
	"encoding/json"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const pkg = "daodanrec"
const lineMax = 1<<20 - 16 // cmd/internal/src keeps a line in 20 bits

const recorder = `// Written by Daodan's go_record.go: see there.
package daodanrec

import (
	"os"
	"runtime"
	"strconv"
	"sync"
)

var (
	out  *os.File
	seen sync.Map
)

func init() {
	if path := os.Getenv("DAODAN_GO_RECORD"); path != "" {
		out, _ = os.OpenFile(path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	}
}

//go:noinline
func Enter(id int) {
	if out == nil {
		return
	}
	var pcs [4]uintptr
	n := runtime.Callers(2, pcs[:])
	if _, dup := seen.LoadOrStore([2]uintptr{pcs[0], pcs[1]}, nil); dup {
		return
	}
	frames := runtime.CallersFrames(pcs[:n])
	frames.Next() // the function entered
	file, line := "", 0
	for {
		frame, more := frames.Next()
		if frame.File != "<autogenerated>" { // a method value's or an embedded method's wrapper
			file, line = frame.File, frame.Line
			break
		}
		if !more {
			break
		}
	}
	out.WriteString(strconv.Itoa(id) + "\t" + file + "\t" + strconv.Itoa(line) + "\n")
}
`

type insertion struct {
	offset int
	text   string
}

type fileTable struct {
	Lines int      `json:"lines"`
	Calls [][3]any `json:"calls"` // line, column, name
}

type table struct {
	Modules   map[string]string    `json:"modules"`   // folder -> module path
	Functions [][4]any             `json:"functions"` // file, line, column, name
	Files     map[string]fileTable `json:"files"`
	Skipped   map[string]string    `json:"skipped"` // file -> why it has no sites, or no rewrite at all
}

func modulePath(root string) (string, error) {
	data, err := os.ReadFile(filepath.Join(root, "go.mod"))
	if err != nil {
		return "", err
	}
	for _, line := range strings.Split(string(data), "\n") {
		fields := strings.Fields(strings.SplitN(line, "//", 2)[0])
		if len(fields) == 2 && fields[0] == "module" {
			return strings.Trim(fields[1], "\"`"), nil
		}
	}
	return "", fmt.Errorf("go.mod names no module")
}

// The name token of a call, as the snapshot reads it: the identifier or the selector's member. Any other callee
// (an index, a call's result, a literal, an instantiation) has no name and is placed where it starts.
func callee(expr ast.Expr) *ast.Ident {
	switch x := expr.(type) {
	case *ast.Ident:
		return x
	case *ast.SelectorExpr:
		return x.Sel
	}
	return nil
}

// The name of a function as the snapshot declares it: `Type.Method` under a receiver.
func named(decl *ast.FuncDecl) string {
	if decl.Recv == nil || len(decl.Recv.List) == 0 {
		return decl.Name.Name
	}
	kind := decl.Recv.List[0].Type
	for {
		switch x := kind.(type) {
		case *ast.StarExpr:
			kind = x.X
			continue
		case *ast.ParenExpr:
			kind = x.X
			continue
		case *ast.IndexExpr:
			kind = x.X
			continue
		case *ast.IndexListExpr:
			kind = x.X
			continue
		case *ast.Ident:
			return x.Name + "." + decl.Name.Name
		}
		return decl.Name.Name
	}
}

// One file of the module at `folder`, rewritten in place; `rel` is its path from the copy root.
func rewrite(root, rel, module string, out *table) error {
	path := filepath.Join(root, filepath.FromSlash(rel))
	src, err := os.ReadFile(path)
	if err != nil {
		return err
	}
	fset := token.NewFileSet()
	file, err := parser.ParseFile(fset, path, src, parser.ParseComments)
	if err != nil {
		out.Skipped[rel] = "the file does not parse: " + strings.SplitN(err.Error(), "\n", 2)[0]
		return nil
	}
	at := func(pos token.Pos) token.Position { return fset.PositionFor(pos, false) }
	lines := fset.File(file.Package).LineCount()
	var bodies, parens []token.Position
	var functions [][4]any
	calls := [][3]any{}
	ast.Inspect(file, func(node ast.Node) bool {
		switch x := node.(type) {
		case *ast.FuncDecl:
			if x.Body != nil {
				bodies = append(bodies, at(x.Body.Lbrace))
				functions = append(functions, [4]any{rel, at(x.Pos()).Line, at(x.Pos()).Column, named(x)})
			}
		case *ast.FuncLit:
			bodies = append(bodies, at(x.Body.Lbrace))
			functions = append(functions, [4]any{rel, at(x.Pos()).Line, at(x.Pos()).Column, "(func)"})
		case *ast.CallExpr:
			name, text := at(x.Fun.Pos()), ""
			if ident := callee(x.Fun); ident != nil {
				name, text = at(ident.Pos()), ident.Name
			}
			parens = append(parens, at(x.Lparen))
			calls = append(calls, [3]any{name.Line, name.Column, text})
		}
		return true
	})
	if len(bodies) == 0 {
		return nil // no function to enter, and the import would be unused
	}
	why := ""
	for _, spec := range file.Imports {
		if spec.Path.Value == `"C"` {
			why = `import "C": cgo prints the file again`
		}
	}
	for _, group := range file.Comments {
		for _, comment := range group.List {
			if strings.HasPrefix(comment.Text, "//line ") || strings.HasPrefix(comment.Text, "/*line ") {
				why = "line directives of its own"
			}
		}
	}
	if why == "" && lines+len(calls) > lineMax {
		why = "more lines and calls than a line number holds"
	}
	if why != "" {
		out.Skipped[rel] = why
		parens, calls = nil, [][3]any{}
	}
	edits := []insertion{{at(file.Name.End()).Offset, fmt.Sprintf("; import %s %q", pkg, module+"/"+pkg)}}
	for n, body := range bodies {
		edits = append(edits, insertion{body.Offset + 1, fmt.Sprintf("%s.Enter(%d);", pkg, len(out.Functions)+n)})
	}
	for n, paren := range parens {
		edits = append(edits, insertion{paren.Offset, fmt.Sprintf("/*line :%d:1*/", lines+1+n)},
			insertion{paren.Offset + 1, fmt.Sprintf("/*line :%d:%d*/", paren.Line, paren.Column+1)})
	}
	sort.SliceStable(edits, func(i, j int) bool { return edits[i].offset < edits[j].offset })
	var text strings.Builder
	last := 0
	for _, edit := range edits {
		text.Write(src[last:edit.offset])
		text.WriteString(edit.text)
		last = edit.offset
	}
	text.Write(src[last:])
	out.Functions = append(out.Functions, functions...)
	out.Files[rel] = fileTable{lines, calls}
	return os.WriteFile(path, []byte(text.String()), 0644)
}

// The Go files of the module at `folder`: not under vendor, testdata, a nested module or a directory the go
// tool ignores.
func sources(root, folder string) ([]string, error) {
	var files []string
	top := filepath.Join(root, filepath.FromSlash(folder))
	err := filepath.Walk(top, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		name := info.Name()
		if info.IsDir() {
			_, own := os.Stat(filepath.Join(path, "go.mod"))
			if path != top && (name == "vendor" || name == "testdata" || name == pkg || own == nil ||
				strings.HasPrefix(name, ".") || strings.HasPrefix(name, "_")) {
				return filepath.SkipDir
			}
			return nil
		}
		if strings.HasSuffix(name, ".go") && !strings.HasPrefix(name, ".") && !strings.HasPrefix(name, "_") {
			rel, _ := filepath.Rel(root, path)
			files = append(files, filepath.ToSlash(rel))
		}
		return nil
	})
	sort.Strings(files)
	return files, err
}

func run(root, target string, folders []string) error {
	out := table{Modules: map[string]string{}, Functions: [][4]any{}, Files: map[string]fileTable{},
		Skipped: map[string]string{}}
	for _, folder := range folders {
		top := filepath.Join(root, filepath.FromSlash(folder))
		module, err := modulePath(top)
		if err != nil {
			return err
		}
		out.Modules[folder] = module
		files, err := sources(root, folder)
		if err != nil {
			return err
		}
		for _, rel := range files {
			if err := rewrite(root, rel, module, &out); err != nil {
				return err
			}
		}
		if err := os.MkdirAll(filepath.Join(top, pkg), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(filepath.Join(top, pkg, "rec.go"), []byte(recorder), 0644); err != nil {
			return err
		}
	}
	data, err := json.Marshal(out)
	if err != nil {
		return err
	}
	return os.WriteFile(target, data, 0644)
}

func main() {
	if len(os.Args) < 4 {
		fmt.Fprintln(os.Stderr, "usage: go_record <copy root> <table.json> <module folder>...")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2], os.Args[3:]); err != nil {
		fmt.Fprintln(os.Stderr, "go_record:", err)
		os.Exit(1)
	}
}
