"""Generate the snapshot reader from the current physical schema metadata.

Direction: this input metadata -> generated_projection.py. Generated Python is a
checked-in application artifact. The database migration and metadata are authored
sources; the generated reader is not a source for either of them.
"""

from pathlib import Path


INPUT_SCHEMA = {'table': 'snapshots', 'columns': ('id', 'resource_key')}


def render():
    columns = ', '.join(INPUT_SCHEMA['columns'])
    statement = f"SELECT {columns} FROM {INPUT_SCHEMA['table']} ORDER BY id"
    return '# Generated by generate_projection.py; do not edit.\n' + \
        f'SNAPSHOT_SELECT = {statement!r}\n'


if __name__ == '__main__':
    Path(__file__).with_name('generated_projection.py').write_text(
        render(), encoding='utf-8', newline='\n')
