def test_the_sites_join_the_snapshots_references_and_close_what_only_a_run_shows(tmp_path):
    project = write_project(tmp_path / "project")
    manifest = tmp_path / "out" / "manifest.sqlite"
    snapshot.read_project(project, manifest)
    sites, _facts = callgrind.read(observation(tmp_path / "observed"), project)
    with code_graph.Snapshot(manifest) as snap:
        rows, facts = dynamic.join(snap, "rust", sites, [], observer)
        names = {identity: (rel, span[0], parts[-1] if parts else "")
                 for identity, rel, _kind, _resolution, _target, span, parts, _reason in snap.references("rust")}
        double, area, closure = (snap.function_at(LIB, 15, 0), snap.function_at(LIB, 10, 4),
                                 snap.function_at(LIB, 25, column(24, "|x|")))
    assert None not in (double, area, closure)
    found: dict = {}
    for row in rows:
        assert row["confidence"] == "observed" and row["resolver"] == dynamic.resolver(observer)
        found.setdefault(names[row["reference_id"]], set()).add((row["verdict"], row["target_id"]))
    assert found[(LIB, 20, "f")] == {("project-callable", double), ("project-callable", closure)}
    assert found[(LIB, 24, "area")] == {("project-callable", area)}
    assert ("project-callable", double) in found[(LIB, 25, "double")]
    assert facts["joined"] >= 4 and facts["recorded"] == len(sites)


