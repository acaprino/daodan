def column(row: int, text: str, nth: int = 0) -> int:
    """The byte column, from 0, of the `nth` `text` in line `row` (from 0)."""
    at = -1
    for _ in range(nth + 1):
        at = ROW[row].index(text, at + 1)
    return at


