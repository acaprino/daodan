def record(*crates: str, workspace=(), toolchains=()) -> dict:
    return {"units": [{"kind": "cargo-crate", "root": root, "name": root.split("/")[-1]} for root in crates],
            "workspace": [{"tool": "cargo", "root": root, "members": list(members)} for root, members in workspace],
            "toolchains": list(toolchains)}


def reader(texts: dict):
    return lambda rel: texts.get(rel, "")


def test_each_crate_or_workspace_with_tests_is_a_run_of_cargo_test():
    files = {"Cargo.toml": "", "src/lib.rs": "#[cfg(test)]\nmod t {\n    #[test]\n    fn a() {}\n}\n",
             "tools/Cargo.toml": "", "tools/tests/it.rs": "fn helper() {}\n"}
    planned = observer.plan(record(".", "tools"), sorted(files), reader(files))
    assert [(run["root"], run["argv"]) for run in planned["runs"]] == [
        (".", observer.ARGV), ("tools", observer.ARGV)]  # an integration test file is a test target
    assert observer.ARGV == ["cargo", "test", "--workspace", "--no-fail-fast"]
    assert planned["gaps"] == []


def test_a_workspace_runs_once_at_its_root_and_a_crate_without_tests_is_a_gap():
    files = {"Cargo.toml": "", "a/Cargo.toml": "", "a/src/lib.rs": "#[tokio::test]\nasync fn t() {}\n",
             "b/Cargo.toml": "", "b/src/lib.rs": "pub fn b() {}\n", "c/Cargo.toml": "", "c/src/main.rs": "fn main() {}\n"}
    planned = observer.plan(record("a", "b", "c", workspace=[(".", ["a", "b"])]), sorted(files), reader(files))
    assert [run["root"] for run in planned["runs"]] == ["."]
    [gap] = planned["gaps"]
    assert (gap["kind"], gap["path"]) == ("no_tests", "c") and "#[test]" in gap["detail"]


def fixture_plan(name: str, extra_units=()) -> dict:
    """The plan of a fixture of benchmarks/project-model, from its expected pre-map (which writes one workspace
    as an object) and its files."""
    fixture = HERE.parent / "benchmarks/project-model/fixtures" / name
    record = json.loads((fixture / "expected.json").read_text(encoding="utf-8"))
    workspace = record.get("workspace") or []
    record = {**record, "units": [*record["units"], *extra_units],
              "workspace": [workspace] if isinstance(workspace, dict) else workspace}
    files = sorted(path.relative_to(fixture).as_posix() for path in fixture.rglob("*") if path.is_file())
    return observer.plan(record, files, lambda rel: (fixture / rel).read_text(encoding="utf-8"))


