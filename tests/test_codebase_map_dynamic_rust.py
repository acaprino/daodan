def test_a_call_is_read_with_its_instructions_address_and_the_address_its_callee_was_entered_at():
    calls = callgrind_sites.parse(CALLGRIND)
    assert len(calls) == 14
    [call] = [call for call in calls if call["callee"] == "<shapes::Square as shapes::Shape>::area"]
    assert call == {"object": OBJECT, "file": f"/work/{LIB}", "function": "shapes::total::{{closure}}",
                    "at": 0x109d08, "line": 24, "callee_object": OBJECT, "callee_file": f"/work/{LIB}",
                    "callee": "<shapes::Square as shapes::Shape>::area", "entered": 0x109f00, "entered_line": 10,
                    "count": 1}
    [drop] = [call for call in calls if call["callee"].startswith("core::ptr")]
    assert drop["callee_file"] == f"{RUSTC}/core/src/ptr/mod.rs"  # `cfi=` holds for its call only
    assert [call["callee_file"] for call in calls if call["callee"] == "shapes::double"] == [f"/work/{LIB}"] * 2


def test_compressed_names_and_relative_positions_are_read_as_callgrind_writes_them_by_default():
    text = ("positions: instr line\nevents: Ir\nob=(1) /work/a.out\nfl=(1) /work/a.c\nfn=(1) main\n0x401000 3 2\n"
            "cfn=(2) helper\ncalls=2 0x401100 9\n+8 +1 40\nfn=(2)\n0x401100 9 3\ncfn=(1)\ncalls=1 0x401000 3\n"
            "* * 7\n")
    first, second = callgrind_sites.parse(text)
    assert (first["callee"], first["at"], first["line"], first["count"]) == ("helper", 0x401008, 4, 2)
    assert (second["function"], second["callee"], second["at"], second["callee_object"]) == (
        "helper", "main", 0x401100, "/work/a.out")


def test_an_objects_load_address_makes_the_entered_addresses_its_function_symbols():
    entered = {call["entered"] for call in callgrind_sites.parse(CALLGRIND) if call["callee_object"] == OBJECT}
    assert callgrind_sites.load_address(entered, SYMBOLS) == BASE
    assert callgrind_sites.load_address({0x401000}, {0x401000, 0x5000}) == 0  # not position-independent
    assert callgrind_sites.load_address(set(), SYMBOLS) is None
    assert callgrind_sites.load_address({0x10a000}, {0x2000, 0x3000}) is None  # two addresses would do
    assert callgrind_sites.load_address({0x10a000, 0x10b000}, {0x2000, 0x3000}) == BASE


